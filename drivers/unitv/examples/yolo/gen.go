//go:build ignore

// gen writes data_unitv.go: the model (model) and the test image already
// converted to the graph's int8 input (input) as string constants for the
// board build. TinyGo 0.43 cannot link //go:embed on the K210 (ld.lld:
// "cannot link object files with different floating-point ABI" between
// the embed objects and the program), while a string constant compiles into
// the program's own rodata: one read-only copy, used in place.
//
//	go run ./drivers/unitv/examples/yolo/gen.go [-model model.tflite] [-input input.u8]
package main

import (
	"bufio"
	"flag"
	"fmt"
	"os"
	"path/filepath"
)

func main() {
	dir := "drivers/unitv/examples/yolo"
	modelPath := flag.String("model", filepath.Join(dir, "model.tflite"), "YOLOX-nano int8 TFLite file")
	inputPath := flag.String("input", filepath.Join(dir, "input.u8"), "416×416×3 uint8 RGB image (raw)")
	out := flag.String("o", filepath.Join(dir, "data_unitv.go"), "output file")
	flag.Parse()
	if err := gen(*out, *modelPath, *inputPath); err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
}

func gen(out, modelPath, inputPath string) error {
	model, err := os.ReadFile(modelPath)
	if err != nil {
		return err
	}
	image, err := os.ReadFile(inputPath)
	if err != nil {
		return err
	}
	if len(image) != 416*416*3 {
		return fmt.Errorf("%s: %d bytes, want %d (416×416×3)", inputPath, len(image), 416*416*3)
	}
	f, err := os.Create(out)
	if err != nil {
		return err
	}
	w := bufio.NewWriter(f)
	fmt.Fprintf(w, "// Code generated by gen.go from %s and %s; DO NOT EDIT.\n\n//go:build unitv\n\npackage main\n\n",
		filepath.Base(modelPath), filepath.Base(inputPath))
	constant(w, "model", model)
	// The graph input is int8 (the cut QUANTIZE: uint8 x → x − 128, which
	// flips the top bit), so the board runs on the constant without a copy.
	for i := range image {
		image[i] ^= 0x80
	}
	constant(w, "input", image)
	if err := w.Flush(); err != nil {
		f.Close()
		return err
	}
	return f.Close()
}

// constant writes `const name = "…"` with every byte hex-escaped.
func constant(w *bufio.Writer, name string, b []byte) {
	const hex = "0123456789abcdef"
	fmt.Fprintf(w, "const %s = \"", name)
	for _, v := range b {
		w.WriteString("\\x")
		w.WriteByte(hex[v>>4])
		w.WriteByte(hex[v&15])
	}
	w.WriteString("\"\n\n")
}
