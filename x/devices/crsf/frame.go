package crsf

import "errors"

const (
	MaxFrameSize = 64
	MinFrameSize = 4 // sync + len + type + crc
	MaxPayload   = 60 // 64 - sync - len - type - crc

	SyncByte byte = 0xC8
)

// Address identifies a CRSF device on the bus.
type Address byte

const (
	AddrBroadcast        Address = 0x00
	AddrUSB              Address = 0x10
	AddrBluetooth        Address = 0x12
	AddrOSD              Address = 0x80
	AddrCurrentSensor    Address = 0xC0
	AddrGPS              Address = 0xC2
	AddrFlightController Address = 0xC8
	AddrRaceTag          Address = 0xCC
	AddrVTX              Address = 0xCE
	AddrRemoteControl    Address = 0xEA
	AddrReceiver         Address = 0xEC
	AddrTransmitter      Address = 0xEE
)

// Type identifies the frame payload type.
type Type byte

const (
	TypeGPS            Type = 0x02
	TypeGPSTime        Type = 0x03
	TypeVario          Type = 0x07
	TypeBattery        Type = 0x08
	TypeBaroAltitude   Type = 0x09
	TypeHeartbeat      Type = 0x0B
	TypeLinkStats      Type = 0x14
	TypeChannelsPacked Type = 0x16
	TypeLinkStatsRX    Type = 0x1C
	TypeLinkStatsTX    Type = 0x1D
	TypeAttitude       Type = 0x1E
	TypeFlightMode     Type = 0x21

	// Extended frame types (dest + origin in payload)
	TypePingDevices    Type = 0x28
	TypeDeviceInfo     Type = 0x29
	TypeParamEntry     Type = 0x2B
	TypeParamRead      Type = 0x2C
	TypeParamWrite     Type = 0x2D
	TypeCommand        Type = 0x32
	TypeTimingCorrect  Type = 0x3A
	TypeMSPRequest     Type = 0x7A
	TypeMSPResponse    Type = 0x7B
)

// IsExtended reports whether frames of this type use the extended header
// (destination + origin addresses in the payload prefix).
func (t Type) IsExtended() bool {
	return t >= 0x28
}

var (
	ErrInvalidSync     = errors.New("crsf: invalid sync byte")
	ErrFrameTooShort   = errors.New("crsf: frame too short")
	ErrFrameTooLong    = errors.New("crsf: frame exceeds max size")
	ErrInvalidLength   = errors.New("crsf: length field out of range")
	ErrCRCMismatch     = errors.New("crsf: CRC mismatch")
	ErrPayloadTooLarge = errors.New("crsf: payload exceeds max size")
	ErrTypeMismatch    = errors.New("crsf: unexpected frame type")
)

// Frame is a decoded CRSF frame with raw payload.
type Frame struct {
	Type    Type
	Payload []byte
}

// Dest returns the destination address for extended frames.
// Returns AddrBroadcast for broadcast frames.
func (f *Frame) Dest() Address {
	if !f.Type.IsExtended() || len(f.Payload) < 2 {
		return AddrBroadcast
	}
	return Address(f.Payload[0])
}

// Origin returns the origin address for extended frames.
// Returns AddrBroadcast for broadcast frames.
func (f *Frame) Origin() Address {
	if !f.Type.IsExtended() || len(f.Payload) < 2 {
		return AddrBroadcast
	}
	return Address(f.Payload[1])
}

// ExtPayload returns the payload without the extended header (dest + origin).
// For broadcast frames, returns the full payload.
func (f *Frame) ExtPayload() []byte {
	if !f.Type.IsExtended() || len(f.Payload) < 2 {
		return f.Payload
	}
	return f.Payload[2:]
}

// Marshal serializes the frame into buf and returns bytes written.
// buf must be at least MaxFrameSize bytes.
func (f *Frame) Marshal(buf []byte) (int, error) {
	frameLen := 2 + len(f.Payload) // type + payload + crc
	total := 2 + frameLen          // sync + len + (type + payload + crc)
	if len(f.Payload) > MaxPayload {
		return 0, ErrPayloadTooLarge
	}
	if len(buf) < total {
		return 0, ErrFrameTooShort
	}

	buf[0] = SyncByte
	buf[1] = byte(frameLen)
	buf[2] = byte(f.Type)
	copy(buf[3:], f.Payload)
	buf[total-1] = CRC8(buf[2 : total-1])
	return total, nil
}

// Unmarshal parses a raw frame from buf. The resulting Payload is a sub-slice
// of buf (zero-copy). Caller must not mutate buf while the Frame is in use.
// Returns the number of bytes consumed from buf.
func (f *Frame) Unmarshal(buf []byte) (int, error) {
	if len(buf) < MinFrameSize {
		return 0, ErrFrameTooShort
	}
	if buf[0] != SyncByte && !isDeviceAddress(buf[0]) {
		return 0, ErrInvalidSync
	}

	frameLen := int(buf[1])
	if frameLen < 2 || frameLen > 62 {
		return 0, ErrInvalidLength
	}

	total := 2 + frameLen
	if len(buf) < total {
		return 0, ErrFrameTooShort
	}

	if CRC8(buf[2:total-1]) != buf[total-1] {
		return 0, ErrCRCMismatch
	}

	f.Type = Type(buf[2])
	payloadLen := frameLen - 2 // subtract type and crc
	if payloadLen > 0 {
		f.Payload = buf[3 : 3+payloadLen]
	} else {
		f.Payload = nil
	}
	return total, nil
}

func isDeviceAddress(b byte) bool {
	switch Address(b) {
	case AddrBroadcast, AddrUSB, AddrBluetooth, AddrOSD,
		AddrCurrentSensor, AddrGPS, AddrFlightController,
		AddrRaceTag, AddrVTX, AddrRemoteControl, AddrReceiver, AddrTransmitter:
		return true
	}
	return false
}

