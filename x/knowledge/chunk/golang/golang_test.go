func lineOf(t *testing.T, src, sub string) int {
	t.Helper()
	for i, l := range strings.Split(src, "\n") {
		if strings.Contains(l, sub) {
			return i + 1
		}
	}
	t.Fatalf("substring %q not in source", sub)
	return 0
}

func span(src string, l0, l1 int) string {
	return strings.Join(strings.Split(src, "\n")[l0-1:l1], "\n")
}

func chunkIt(t *testing.T, c *Chunker, id, src string) knowledge.ChunkResult {
	t.Helper()
	doc := knowledge.DocID(id)
	res, err := c.Chunk(knowledge.Doc{ID: doc, Kind: "go"}, []byte(src))
	if err != nil {
		t.Fatalf("Chunk: %v", err)
	}
	for i, ch := range res.Chunks {
		if ch.Ord != i || ch.Doc != doc {
			t.Errorf("chunk %d: Ord=%d Doc=%q", i, ch.Ord, ch.Doc)
		}
		if want := span(src, ch.Lines[0], ch.Lines[1]); ch.Text != want {
			t.Errorf("chunk %d: Text does not match span %v:\n got %q\nwant %q", i, ch.Lines, ch.Text, want)
		}
		if ch.ID != knowledge.NewChunkID(doc, i, ch.Text) || ch.Hash != sha256.Sum256([]byte(ch.Text)) || ch.Tokens != token.Count(ch.Text) {
			t.Errorf("chunk %d: id/hash/tokens mismatch", i)
		}
	}
	return res
}

type want struct {
	symbol  string
	heading []string
	from    string // substring of the first line
	to      string // substring of the last line
}

const src = `// Code generated by stringer; DO NOT EDIT.

// Package keys manages peer keys.
//
// More package docs.
package keys

import (
	"fmt"
	str "strings"
)

// Version is the version.
const Version = "1"

// Group doc.
const (
	A, B = 1, 2
	_    = 3
)

var x int

// Peer is a peer.
type Peer struct {
	Name string
}

// Types doc.
type (
	// Alpha doc.
	Alpha int // trailing

	Beta[T any] struct{ v T }
)

// Hello says hello.
func Hello() string { return fmt.Sprint(str.ToUpper("x")) }

// Greet greets.
//
// Long doc.
func (p *Peer) Greet() {
	_ = p
}

func (b Beta[T]) Get() T { return b.v }

func init() {}

func init() {}
`

func TestAccepts(t *testing.T) {
	c := New()
	for path, w := range map[string]bool{"a.go": true, "a_test.go": true, "x/A.GO": true, "a.go.txt": false, "go": false, "a.md": false} {
		if got := c.Accepts(path); got != w {
			t.Errorf("Accepts(%q) = %v, want %v", path, got, w)
		}
	}
}

func TestChunks(t *testing.T) {
	res := chunkIt(t, New(), "abugaga/keys/keys.go", src)
	if res.Title != "keys" {
		t.Errorf("Title = %q", res.Title)
	}
	wantProps := map[string]string{"package": "keys", "generated": "true"}
	if !reflect.DeepEqual(res.Props, wantProps) {
		t.Errorf("Props = %v, want %v", res.Props, wantProps)
	}
	wants := []want{
		{"", []string{"keys"}, "// Package keys manages", ")"},
		{"keys.Version", nil, "// Version is", "const Version"},
		{"keys.A", nil, "// Group doc.", ")"},
		{"keys.x", nil, "var x int", "var x int"},
		{"keys.Peer", nil, "// Peer is a peer.", "}"},
		{"keys.Alpha", nil, "// Types doc.", "Alpha int"},
		{"keys.Beta", nil, "Beta[T any]", ")"},
		{"keys.Hello", nil, "// Hello says", "func Hello"},
		{"keys.Peer.Greet", nil, "// Greet greets.", "}"},
		{"keys.Beta.Get", nil, "func (b Beta[T]) Get", "func (b Beta[T]) Get"},
		{"keys.init", nil, "func init", "func init"},
		{"keys.init", nil, "func init", "func init"},
	}
	if len(res.Chunks) != len(wants) {
		for _, c := range res.Chunks {
			t.Logf("%q %v %v", c.Symbol, c.Heading, c.Lines)
		}
		t.Fatalf("got %d chunks, want %d", len(res.Chunks), len(wants))
	}
	lines := strings.Split(src, "\n")
	for i, w := range wants {
		c := res.Chunks[i]
		if c.Symbol != w.symbol {
			t.Errorf("chunk %d: Symbol = %q, want %q", i, c.Symbol, w.symbol)
		}
		wh := w.heading
		if wh == nil {
			wh = []string{"keys", w.symbol}
		}
		if !slices.Equal(c.Heading, wh) {
			t.Errorf("chunk %d: Heading = %q, want %q", i, c.Heading, wh)
		}
		if !strings.Contains(lines[c.Lines[0]-1], w.from) || !strings.Contains(lines[c.Lines[1]-1], w.to) {
			t.Errorf("chunk %d (%s): span %v = %q..%q, want lines containing %q..%q",
				i, w.symbol, c.Lines, lines[c.Lines[0]-1], lines[c.Lines[1]-1], w.from, w.to)
		}
	}
	// Exact spans for a few, asserted as numbers.
	if got, w := res.Chunks[0].Lines, [2]int{3, lineOf(t, src, "str \"strings\"") + 1}; got != w {
		t.Errorf("header span = %v, want %v (includes closing paren)", got, w)
	}
	if got, w := res.Chunks[6].Lines, [2]int{lineOf(t, src, "Beta[T any]"), lineOf(t, src, "Beta[T any]") + 1}; got != w {
		t.Errorf("Beta span = %v, want %v (includes closing paren)", got, w)
	}
	if got, w := res.Chunks[8].Lines, [2]int{lineOf(t, src, "// Greet greets."), lineOf(t, src, "_ = p") + 1}; got != w {
		t.Errorf("Greet span = %v, want %v", got, w)
	}
	if !strings.Contains(res.Chunks[5].Text, "// trailing") {
		t.Errorf("Alpha chunk should keep its line comment: %q", res.Chunks[5].Text)
	}
}

func TestEdges(t *testing.T) {
	res := chunkIt(t, New(), "abugaga/keys/keys.go", src)
	from := knowledge.DocNode("abugaga/keys/keys.go")
	var got []string
	for _, e := range res.Edges {
		if e.From != from || e.Source != "abugaga/keys/keys.go" || e.Weight != 1 {
			t.Errorf("edge %+v: wrong From/Source/Weight", e)
		}
		got = append(got, e.Kind.String()+" "+string(e.To))
	}
	w := []string{
		"imports pkg:fmt",
		"imports pkg:strings",
		"defines sym:keys.Version",
		"defines sym:keys.A",
		"defines sym:keys.B",
		"defines sym:keys.x",
		"defines sym:keys.Peer",
		"defines sym:keys.Alpha",
		"defines sym:keys.Beta",
		"defines sym:keys.Hello",
		"defines sym:keys.Peer.Greet",
		"defines sym:keys.Beta.Get",
		"defines sym:keys.init",
	}
	if !slices.Equal(got, w) {
		t.Errorf("edges =\n%s\nwant\n%s", strings.Join(got, "\n"), strings.Join(w, "\n"))
	}
	if len(res.Links) != 0 {
		t.Errorf("Links = %v, want none", res.Links)
	}
}

func TestProps(t *testing.T) {
	tests := []struct {
		name, id, src string
		props         map[string]string
		header        [2]int
	}{
		{"plain", "a/b.go", "package b\n\nfunc F() {}\n", map[string]string{"package": "b"}, [2]int{1, 1}},
		{"test file", "a/b_test.go", "package b_test\n\nimport \"testing\"\n\nfunc TestX(t *testing.T) {}\n", map[string]string{"package": "b_test", "test": "true"}, [2]int{1, 3}},
		{"generated mid-comment is not generated", "g.go", "// Package g. Code generated by x DO NOT EDIT.\npackage g\n", map[string]string{"package": "g"}, [2]int{1, 2}},
		{"generated", "g.go", "// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage g\n", map[string]string{"package": "g", "generated": "true"}, [2]int{3, 3}},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			res := chunkIt(t, New(), tt.id, tt.src)
			if !reflect.DeepEqual(res.Props, tt.props) {
				t.Errorf("Props = %v, want %v", res.Props, tt.props)
			}
			if len(res.Chunks) == 0 || res.Chunks[0].Lines != tt.header {
				t.Errorf("header span: chunks %+v, want %v", res.Chunks, tt.header)
			}
		})
	}
}

func TestSplitLongDecl(t *testing.T) {
	var b strings.Builder
	b.WriteString("package p\n\n// Big is big.\nfunc Big() {\n")
	for i := range 6 {
		fmt.Fprintf(&b, "\tx%d := a + b\n\t_ = x%d\n\n", i, i) // 8 tokens per block
	}
	b.WriteString("}\n")
	s := b.String()
	res := chunkIt(t, New(WithMaxTokens(20)), "p.go", s)
	// header, then Big split: "// Big is big." (4) + "func Big() {" (3) + x0 (8) = 15; + x1 = 23 > 20.
	wantSpans := [][2]int{
		{1, 1},
		{lineOf(t, s, "// Big"), lineOf(t, s, "_ = x0")},
		{lineOf(t, s, "x1 :="), lineOf(t, s, "_ = x2")},
		{lineOf(t, s, "x3 :="), lineOf(t, s, "_ = x4")},
		{lineOf(t, s, "x5 :="), lineOf(t, s, "_ = x5") + 2},
	}
	var got [][2]int
	for i, c := range res.Chunks {
		got = append(got, c.Lines)
		if i > 0 && (c.Symbol != "p.Big" || !slices.Equal(c.Heading, []string{"p", "p.Big"})) {
			t.Errorf("chunk %d: symbol %q heading %q", i, c.Symbol, c.Heading)
		}
	}
	if !reflect.DeepEqual(got, wantSpans) {
		t.Errorf("spans = %v, want %v", got, wantSpans)
	}
	if n := len(res.Edges); n != 1 {
		t.Errorf("edges = %d, want 1 (split must not duplicate Defines)", n)
	}
}

func TestParseErrorFallback(t *testing.T) {
	var b strings.Builder
	b.WriteString("package broken\n\nfunc {{{ oops\n")
	for i := 4; i <= 130; i++ {
		fmt.Fprintf(&b, "line %d\n", i)
	}
	s := strings.TrimSuffix(b.String(), "\n")
	res := chunkIt(t, New(), "x/broken.go", s)
	wantSpans := [][2]int{{1, 60}, {51, 110}, {101, 130}}
	var got [][2]int
	for _, c := range res.Chunks {
		got = append(got, c.Lines)
		if !slices.Equal(c.Heading, []string{"broken.go"}) || c.Symbol != "" {
			t.Errorf("fallback chunk heading %q symbol %q", c.Heading, c.Symbol)
		}
	}
	if !reflect.DeepEqual(got, wantSpans) {
		t.Errorf("spans = %v, want %v", got, wantSpans)
	}
	if len(res.Edges) != 0 {
		t.Errorf("edges = %v, want none", res.Edges)
	}
	if res.Title != "broken" || res.Props["package"] != "broken" {
		t.Errorf("Title = %q Props = %v", res.Title, res.Props)
	}

	res = chunkIt(t, New(), "x/short.go", "not go at all\n")
	if len(res.Chunks) != 1 || res.Chunks[0].Lines != [2]int{1, 1} || res.Title != "short" {
		t.Errorf("short fallback: title %q chunks %+v", res.Title, res.Chunks)
	}
}

func TestLineDirectivesIgnored(t *testing.T) {
	s := "package g\n\n//line grammar.y:500\nfunc Parse() int {\n\treturn 1\n}\n\nfunc After() {}\n"
	res := chunkIt(t, New(), "g/parse.go", s)
	var got []string
	for _, c := range res.Chunks {
		got = append(got, fmt.Sprintf("%s %v", c.Symbol, c.Lines))
	}
	// The //line comment is adjacent to Parse, so it is part of its doc group.
	w := []string{" [1 1]", "g.Parse [3 6]", "g.After [8 8]"}
	if !slices.Equal(got, w) {
		t.Errorf("chunks = %q, want %q", got, w)
	}
}
